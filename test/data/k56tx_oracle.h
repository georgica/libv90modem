/* test/data/k56tx_oracle.h: D-Modem's K56flex training as an oracle.
 *
 * Generated outside this repository by ~/modem-research/k56-oracle/train
 * (ours), which links D-Modem's K56Train, K56Enc and V34Mp::build
 * (github.com/D-Modem/D-Modem at c06a380d, AGPL-3.0, unmodified) and
 * drives them as its v34_k56.h does, at fixed symbols. No D-Modem code
 * is here: only its output, as data (docs/history/k56-facts.md
 * "Oracle").
 *
 * Each case: mu-law, J word 0x89b0 (16-level Js), from silence 1.
 *   - j_at: after j_at symbols of silence 2 the client's J (octet
 *     j_octet: pad bits 6-7, robbed bits 0-5) arrives; silence 2 is then
 *     max(12288, j_at rounded up to 8) symbols, R2 at once when that
 *     many are sent already.
 *   - mp_at: after mp_at symbols of TRN2B the client's MP arrives; our MP
 *     and MP' are k56tx_oracle_mp[0] and [1] (V.34 type 0: rate_ca 13,
 *     rate_ac 13 (56000 bit/s), mask 0x3fff, asymmetric; 88 bits, octets
 *     least significant bit first); TRN2B ends at the first symbol with
 *     the MP in, at least 2048 of TRN2B sent and (symbols from TRN1B's
 *     first + 1420, 1432 in a renegotiation) % 24 == 0.
 *   - the data encoder starts at the MP (rate code 13, the J's pad and
 *     robbed bits); the first data frame is B1's first (all-one data
 *     bits, scrambled by the encoder's own GPA from state 0).
 *   - reneg 1: the first training as case (j_octet, j_at, mp_at 3000)
 *     through its first data frame, then data to 1001 frames in all (B1,
 *     then any bits: only the count matters), then at that frame
 *     boundary the renegotiation from R2: TRN2A 2048, MARK, TRN2B, the
 *     client's MP at mp_at of TRN2B (TRN2B still at least 2048), MP and
 *     MP' 1 bit a symbol, E 24, the training's scrambler, history and
 *     running sum carried on from the first E, a new data encoder
 *     (Ruling C4: every MP restarts it), B1 again. Recorded from R2.
 * k56tx_oracle_seg[case][segment] (segments in the order of K56TX_SIL1 ..
 * K56TX_DATA): the segment's length in symbols, FNV-1a (32 bits) of its
 * mu-law octets and its first 8 octets (0 past its length); DATA is the
 * first data frame only. Segments not sent: length 0. */
