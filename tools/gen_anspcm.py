#!/usr/bin/env python3
"""Generate modem/qc_tab.c: ANSpcm's 301 codewords at each of the four
levels of Table 6/V.92, both laws (qc_anspcm, modem/qc.h), from 8.3.1's
formula:
  x = scl * sqrt(2) * cos(2 pi k 79 / 301 + theta) + 0.5,  k = 0 .. 300,
  theta = 0.25 pi / 301,
  scl: -9.5 dBm0 mu 1334, A 667; -12 mu 1000, A 500; -15 mu 708, A 354;
       -18 mu 500, A 250,
x floored to an integer, then quantised by G.711 (the 14-bit mu-law scale,
+-8159, and the 13-bit A-law one, +-4096, the encoder truncating), the
octets as sent: mu-law inverted, A-law with its even bits inverted, the
sign bit 1 for a positive value. This convention reproduces all 2408
entries of Tables 7 to 10 (truncation toward zero: 96 differ, rounding:
118; docs/history/qc-facts.md, ANSpcm). The library uses the table only,
never libm.

Run: python3 tools/gen_anspcm.py > modem/qc_tab.c
     python3 tools/gen_anspcm.py --check <the V.92 text>
the second compares the formula with the tables read from the
Recommendation's text and prints how many entries are equal (it writes
nothing).
"""
import math
import re
import sys

SCL = ((1334, 1000, 708, 500), (667, 500, 354, 250))   # [law][level]
LEVELS = ("-9.5", "-12", "-15", "-18")


def ulaw(v):
    """G.711 mu-law of a 14-bit linear value, as the octet sent"""
    pos = v >= 0
    m = min(abs(v), 8158) + 33
    seg = 0
    while (m >> (seg + 6)) != 0 and seg < 7:
        seg += 1
    u = (seg << 4) | ((m >> (seg + 1)) & 15)
    return (0xFF - u) if pos else (0x7F - u)


def alaw(v):
    """G.711 A-law of a 13-bit linear value, as the octet sent"""
    pos = v >= 0
    m = min(abs(v), 4095)
    if m < 32:
        c = m >> 1
    else:
        seg = 1
        while seg < 7 and m >= (32 << seg):
            seg += 1
        c = (seg << 4) | ((m >> seg) & 15)
    if pos:
        c |= 0x80
    return c ^ 0x55


def table(law, level):
    out = []
    th = 0.25 * math.pi / 301
    for k in range(301):
        x = SCL[law][level] * math.sqrt(2) * math.cos(2 * math.pi * k * 79 / 301 + th) + 0.5
        v = math.floor(x)
        out.append(alaw(v) if law else ulaw(v))
    return out


def parse_text(path):
    """Tables 7 to 10 from the V.92 text: {(law, level): [301 octets]}.
    Each row has seven (k, mu, A) triples, k = r, r + 43, ... r + 258; an
    octet may have lost its leading zero ("8" for 08)."""
    lines = open(path, encoding="utf-8", errors="replace").read().split("\n")
    got = {}
    level = None
    for ln in lines:
        m = re.search(r"Table (7|8|9|10)/V\.92 . .?[0-9.]+ dBm0 ANSpcm sequence", ln)
        if m:
            level = int(m.group(1)) - 7
            got[(0, level)] = [None] * 301
            got[(1, level)] = [None] * 301
            continue
        if level is None:
            continue
        if re.match(r"^\s*8\.3\.2\b", ln):
            break
        t = ln.split()
        if len(t) != 21 or not all(x.isdigit() for x in t[0::3]):
            continue
        ks = [int(x) for x in t[0::3]]
        r = ks[0]
        if r > 42 or ks != [r + 43 * j for j in range(7)]:
            continue
        for j in range(7):
            got[(0, level)][ks[j]] = int(t[3 * j + 1], 16)
            got[(1, level)][ks[j]] = int(t[3 * j + 2], 16)
    return got


def check(path):
    got = parse_text(path)
    total = equal = missing = 0
    for law in (0, 1):
        for level in range(4):
            ref = got.get((law, level), [None] * 301)
            mine = table(law, level)
            for k in range(301):
                total += 1
                if ref[k] is None:
                    missing += 1
                elif ref[k] == mine[k]:
                    equal += 1
                else:
                    print("Table %d %s k %d: text %02X, formula %02X"
                          % (7 + level, "A" if law else "mu", k, ref[k], mine[k]))
    print("%d of %d entries equal%s" % (equal, total,
          "" if not missing else " (%d not read from the text)" % missing))
    return 0 if equal == total == 2408 else 1


def generate():
    print("/* GENERATED by tools/gen_anspcm.py - do not edit. */")
    print("#include \"qc.h\"")
    print("")
    print("/* ANSpcm (8.3.1/V.92, Tables 7 to 10): [law: 0 mu, 1 A][LM][k], the")
    print(" * octets as sent */")
    print("const uint8_t qc_anspcm[2][4][QC_ANSPCM_PERIOD] = {")
    for law in (0, 1):
        print("  {")
        for level in range(4):
            v = table(law, level)
            print("    {   /* %s dBm0, %s */" % (LEVELS[level], "A-law" if law else "mu-law"))
            for r in range(0, 301, 16):
                print("      " + ",".join("0x%02X" % x for x in v[r:r + 16]) + ",")
            print("    }," if level < 3 else "    }")
        print("  }," if law == 0 else "  }")
    print("};")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        sys.exit(check(sys.argv[2]))
    if len(sys.argv) != 1:
        sys.stderr.write("usage: gen_anspcm.py [--check <V.92 text>]\n")
        sys.exit(2)
    generate()
