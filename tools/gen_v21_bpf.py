#!/usr/bin/env python3
"""Receive band-passes for V.21, Kaiser-windowed sinc, linear phase. Pure python.
Default: the low channel (980 / 1180 Hz) of the answering modem, which keeps
the echo of our own high channel (1650 / 1850 Hz) and of ANSam (2100 Hz) out
of its carrier detector: writes modem/v21_bpf.h. --high: the high channel
(1650 / 1850 Hz) of the calling modem, keeping the echo of its own low channel
out: writes modem/v21h_bpf.h."""
import math, sys

FS = 8000.0
N = 81
HIGH = "--high" in sys.argv
LO, HI = (1430.0, 2070.0) if HIGH else (760.0, 1400.0)     # -6 dB points
CENTRE = 1750.0 if HIGH else 1080.0
NAME, FILE, WHAT = ("v21h_bpf", "modem/v21h_bpf.h", "high") if HIGH else ("v21_bpf", "modem/v21_bpf.h", "low")
BETA = 4.5

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s

def taps():
    h = []
    m = (N - 1) / 2.0
    for n in range(N):
        t = n - m
        if t == 0:
            v = 2 * (HI - LO) / FS
        else:
            v = (math.sin(2 * math.pi * HI * t / FS) - math.sin(2 * math.pi * LO * t / FS)) / (math.pi * t)
        w = i0(BETA * math.sqrt(1 - (t / m) ** 2)) / i0(BETA)
        h.append(v * w)
    return h

def gain(h, f):
    re = sum(c * math.cos(2 * math.pi * f * n / FS) for n, c in enumerate(h))
    im = sum(c * math.sin(2 * math.pi * f * n / FS) for n, c in enumerate(h))
    return math.hypot(re, im)

h = taps()
g0 = gain(h, CENTRE)
q = [int(round(c / g0 * 32768)) for c in h]
hq = [c / 32768.0 for c in q]
def db(f): return 20 * math.log10(max(gain(hq, f), 1e-9))
report = {f: db(f) for f in (300, 600, 880, 980, 1080, 1180, 1280, 1500, 1650, 1850, 2100, 2225)}
if "--check" in sys.argv:
    for f, v in report.items(): print("%5d Hz %7.2f dB" % (f, v))
    sys.exit(0)
out = ["/* Generated by tools/gen_v21_bpf.py: do not edit.",
       " * V.21 %s-channel receive band-pass, %d taps, Q15, linear phase." % (WHAT, N),
       " * Response: " + ", ".join("%d Hz %.1f dB" % (f, v) for f, v in report.items() if f in (980, 1180, 1650, 1850, 2100)) + " */",
       "#ifndef V90D_MODEM_%s_H" % NAME.upper(), "#define V90D_MODEM_%s_H" % NAME.upper(), "#include <stdint.h>",
       "#define %s_N %d" % (NAME.upper(), N), "static const int16_t %s[%s_N] = {" % (NAME, NAME.upper())]
for i in range(0, N, 9):
    out.append("    " + ", ".join("%6d" % v for v in q[i:i + 9]) + ",")
out += ["};", "#endif", ""]
open(FILE, "w").write("\n".join(out))
