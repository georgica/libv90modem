#!/usr/bin/env python3
"""Generate modem/pcmtx_tab.h: the fractional-delay bank of the V.92 PCM
upstream transmitter (modem/pcmtx), symbols on the network clock -> samples
on ours.

A PCM upstream reaches to the band edge, and what a bank gets wrong there
changes as the two clocks turn against each other: a channel the digital
modem measured once and does not follow. No bank of reasonable length is
right up to 4 kHz (modem/v34_tabs.h's 64 taps: -74 dB to 3.7 kHz, -9 dB at
3.9 kHz; see docs/history/PROGRESS.md, C6-2), so this one is a low-pass as well: a sinc
cut at 3700 Hz in a 64 tap Kaiser window: -1.7 dB at 3600 Hz, -15 dB at 3800
Hz, -31 dB at 3900 Hz, and every branch within -78 dB of the others at every
frequency of the band. The far codec's filters (G.712) cut there anyway;
what is left is one fixed response, which the digital modem measures with
the line. Not sharper: a sharper cut rings for longer, and the ringing
before the main tap must stay inside what the digital modem's channel
estimate spans (24 symbols ahead of the cursor in ours): beyond 24 taps from
the centre this one has -64 dB of its energy (a 128 tap cut at 3850 Hz:
-39 dB, and the upstream failed on a line that passes the band edge).
The transmitter interpolates linearly between adjacent branches. Branch p,
tap i weights the symbol i places behind the newest one it is laid on and
yields the signal 31 + p/32 symbols before it; unity gain at DC.
Run: python3 tools/gen_pcmtx_tab.py > modem/pcmtx_tab.h
"""
import math

P, N, D, BETA = 32, 64, 31, 7.5
FC = 3700.0 / 4000.0        # the cut, as a part of the band

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s

def kaiser(u):          # u in [-1, 1]
    return i0(BETA * math.sqrt(1 - u * u)) / i0(BETA) if abs(u) < 1 else 0.0

def sinc(t):
    return 1.0 if abs(t) < 1e-12 else math.sin(math.pi * t) / (math.pi * t)

out = ["/* GENERATED by tools/gen_pcmtx_tab.py - do not edit. */",
       "#ifndef V90D_MODEM_PCMTX_TAB_H", "#define V90D_MODEM_PCMTX_TAB_H", "#include <stdint.h>", "",
       "#define PCMTX_IP %d      /* fractional-delay branches */" % P,
       "#define PCMTX_IN %d     /* taps per branch */" % N,
       "#define PCMTX_ID %d      /* whole-symbol delay of the bank */" % D,
       "/* Q14, unity gain at DC */",
       "static const int16_t pcmtx_interp[PCMTX_IP + 1][PCMTX_IN] = {"]
for p in range(P + 1):      # branch P (one whole symbol) closes the interpolation between branches
    h = [FC * sinc(FC * (i - D - p / P)) * kaiser((i - D - p / P) / (N / 2.0)) for i in range(N)]
    s = sum(h)
    q = [round(v / s * 16384) for v in h]
    # the rounding must not move the DC gain: put what is missing on the largest tap
    k = max(range(N), key=lambda i: abs(q[i]))
    q[k] += 16384 - sum(q)
    out.append("  {" + ",".join("%d" % v for v in q) + "},")
out.append("};")
out.append("#endif")
print("\n".join(out))
