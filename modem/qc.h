/* V.92 Quick Connect, the digital modem's signals (8.2, 8.3, 9.2.4): the
 * caller's QC1a octet (Table 2) and its UQTS, our QCA1d (Table 13), the
 * ANSpcm level LM, QTS and QTS\ (8.3.6) and ANSpcm (8.3.1, Tables 7 to 10).
 * The values are in docs/history/qc-facts.md ("Short Phase 1", "UQTS",
 * "ANSpcm", "QTS", "Readings").
 *
 * Written from the V.92 text, apart from the simulated caller (sim/qca) on
 * purpose: the two are tested against each other (test/test_qcsig.c).
 *
 * An information octet is the eight data bits of the 10-bit character of
 * bits 20:29 (and 50:59), the first in time in bit 0: bit 0 analogue (0) or
 * digital (1), bit 1 QC (0) or QCA (1), bit 2 P (LAPM), bit 4 always 0;
 * QC1a has W X Y Z in bits 3, 5, 6, 7, QCA1d L M in bits 6, 7.
 *
 * Pure functions and const tables, integer only. */
#ifndef V90D_MODEM_QC_H
#define V90D_MODEM_QC_H
#include <stdint.h>

#define QC_SYNC         0x55    /* 0101010101 as a character */
#define QC_OCT_DIGITAL  0x01    /* bit 21: a digital modem */
#define QC_OCT_ACK      0x02    /* bit 22: QCA (an answer to QC) */
#define QC_OCT_LAPM     0x04    /* bit 23: P, LAPM asked for (9.2.5) */
#define QC_OCT_ZERO     0x10    /* bit 25 of Tables 2 and 13, always 0 */
#define QC_WXYZ_ONHOLD  15      /* WXYZ 1111: cleardown from on-hold, no UQTS */

#define QC_FRAME_BITS   60      /* QC1a: two copies of 30 bits */
#define QC_FRAME_BITS_T 70      /* QCA1x: and ten ONEs */
#define QC_QTS_LEN      768     /* QTS: 128 x 6 symbols */
#define QC_QTSB_LEN     48      /* QTS\: 8 x 6 symbols */
#define QC_ANSPCM_PERIOD 301
#define QC_ANSPCM_REV   3612    /* the sign inverted in every other block of this */

/* UQTS's Ucode for WXYZ 0..14 (Table 2): 61..87; -1 for 15 and anything else */
int qc_uqts_ucode(int wxyz);

/* a QC1a information octet: 0 when bits 0, 1 and 4 are clear (an analogue
 * modem's QC), with *wxyz = 8W + 4X + 2Y + Z (bits 3, 5, 6, 7) and *lapm =
 * P (bit 2); -1 otherwise, *wxyz and *lapm untouched. WXYZ 15 is returned
 * as it is (QC_WXYZ_ONHOLD): the caller decides. */
int qc1a_parse(uint8_t oct, int *wxyz, int *lapm);

/* QCA1d's information octet (Table 13): digital, QCA, P = lapm, L M = lm */
uint8_t qca1d_octet(int lm, int lapm);

/* the frame of an information octet: twice {ten ONEs, 0101010101, start 0,
 * the octet's bits 0..7, stop 1}, and with trailing_ones ten ONEs more
 * (QCA1d). bits[] gets one bit a byte, the first in time first; returns 60
 * or 70. */
int qc_frame_bits(uint8_t oct, int trailing_ones, uint8_t *bits);

/* the ANSpcm level (LM 0..3: -9.5, -12, -15, -18 dBm0) for a nominal
 * Phase 2 transmit power of tx_dbm0 dBm0: the nearest (ties to the lower),
 * then the next lower while above the maximum INFO0d advertises, -0.5 -
 * 0.5 x max_tx_code dBm0; never below LM 3 (Readings 3) */
int qc_lm(int tx_dbm0, int max_tx_code);
/* LM's level in 0.1 dBm0: -95, -120, -150, -180 */
int qc_lm_db10(int lm);

/* QTS (i 0..767: {+V, +0, +V, -V, -0, -V}) and QTS\ (i 768..815: {-V, -0,
 * -V, +V, +0, +V}), V the codeword of Ucode ucode, as the octet sent */
uint8_t qc_qts_octet(int alaw, int ucode, int i);

/* ANSpcm, octets as sent: [alaw][lm][k] (modem/qc_tab.c, generated by
 * tools/gen_anspcm.py) */
extern const uint8_t qc_anspcm[2][4][QC_ANSPCM_PERIOD];
/* ANSpcm's codeword n (n >= 0; 0 the first): k = n % 301, bit 7 inverted
 * when n / 3612 is odd */
uint8_t qc_anspcm_octet(int alaw, int lm, int32_t n);

#endif
