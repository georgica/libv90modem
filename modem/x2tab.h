/* x2's level tables: levels A (the start-up's sync and records) and the
 * data banks, per pad mode and rate index (docs/history/x2-facts.md,
 * "Mapping", "Pads", "Banks"). x2tab.c and x2bank.c say where each comes
 * from. Lists hold positive mu-law octets, the largest magnitude first
 * (the smallest octet first). */
#ifndef V90D_MODEM_X2TAB_H
#define V90D_MODEM_X2TAB_H
#include <stdint.h>

#define X2_NLEV1 9                      /* levels per position in levels A */

extern const uint8_t x2_levels_a[X2_NLEV1];   /* sync, records, the start's first frame */

/* The data banks (x2bank.c, generated by tools/gen_x2_banks.py): for pad
 * mode m (0 none, 1 3 dB, 2 6 dB, as the client's MP reports it) and rate
 * index n (1..15), x2_banks[m][n - 1]: B bits a frame (and MD = 5 signs),
 * the list of position 0 and the list of positions 1..5. A list is n
 * entries in x2_bank_pool: the level the client receives at recv + d, the
 * octet sent for it across the pad at sent + d. Rate index 1 in mode 0 is
 * levels B. */
#define X2_MODES 3
#define X2_NIDX  15
typedef struct { uint16_t recv, sent; uint8_t n; } x2_list_t;
typedef struct { uint8_t b; uint8_t list[2]; } x2_bank_t;
extern const uint8_t   x2_bank_pool[];
extern const x2_list_t x2_bank_lists[];
extern const x2_bank_t x2_banks[X2_MODES][X2_NIDX];

#endif
